namespace Wunschzettu.Api.Data;

public enum ListAccess { Link, Invited }
public enum WishState { Active, Fulfilled, Removed }
public enum ListLayout { Grid, List }
public enum Palette { Classic, Forest, Ocean, Berry, Sunset, Night }
public enum GiftStatus { Planned, Bought }
/// Where a wish can be bought: a web shop (URL) or a physical store (name, place).
public enum LinkKind { Online, Store }

public class Wishlist
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public required string Title { get; set; }
    public string? Description { get; set; }
    /// The "Für wen?" label. Who actually is recipient lives on <see cref="ListMember.IsRecipient"/>.
    public string? RecipientName { get; set; }
    public DateOnly? EventDate { get; set; }
    public string Currency { get; set; } = "CHF";
    public required string ShareToken { get; set; }
    public ListAccess Access { get; set; } = ListAccess.Link;
    public bool ShowGiverNames { get; set; } = true;
    public Theme Theme { get; set; } = new();
    public DateTime CreatedAt { get; set; }
    public DateTime UpdatedAt { get; set; }
    public DateTime? DeletedAt { get; set; }

    /// Jobs remember which event date they already handled, so changing the date re-arms them (§6).
    public DateOnly? EventReminderSentFor { get; set; }
    public DateOnly? EventProcessedFor { get; set; }

    public List<ListMember> Members { get; set; } = [];
    public List<Wish> Wishes { get; set; } = [];
}

/// Presets only (§10).
public class Theme
{
    public Palette Palette { get; set; } = Palette.Classic;
    public string? Emoji { get; set; }
    public ListLayout Layout { get; set; } = ListLayout.Grid;
}

/// Managers, recipients, and guests who acted on (or were invited to) the list.
public class ListMember
{
    public Guid WishlistId { get; set; }
    public required string UserId { get; set; }
    public bool IsManager { get; set; }
    public bool IsRecipient { get; set; }
    /// Guests a manager invited explicitly. Guests who joined by acting are never listed: that would leak gift activity to recipients.
    public bool Invited { get; set; }
    public DateTime JoinedAt { get; set; }

    public bool IsGuest => !IsManager && !IsRecipient;

    public Wishlist Wishlist { get; set; } = null!;
    public AppUser User { get; set; } = null!;
}

public class Wish
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public Guid WishlistId { get; set; }
    public required string Name { get; set; }
    public string? Description { get; set; }
    public decimal? Price { get; set; }
    /// EAN/UPC barcode number, to find the same product in other shops.
    public string? Gtin { get; set; }
    public bool IsFavorite { get; set; }
    /// null = unlimited
    public int? Quantity { get; set; } = 1;
    public bool GroupGiftAllowed { get; set; }
    public WishState State { get; set; } = WishState.Active;
    public int SortOrder { get; set; }
    /// Concurrency token for every gift operation (§6.8). Bumped automatically on save.
    public int Version { get; set; }
    public DateTime CreatedAt { get; set; }

    public Wishlist Wishlist { get; set; } = null!;
    public List<WishLink> Links { get; set; } = [];
    public List<WishImage> Images { get; set; } = [];
    public List<Gift> Gifts { get; set; } = [];
}

public class WishLink
{
    /// Generated by EF on insert: links are replaced wholesale, and a preset key would make EF update instead of insert.
    public Guid Id { get; set; }
    public Guid WishId { get; set; }
    public LinkKind Kind { get; set; }
    /// Store name (required for stores) or an optional shop name for online links.
    public string? Label { get; set; }
    /// Online links only.
    public string? Url { get; set; }
    public string? Note { get; set; }
    public int SortOrder { get; set; }

    /// Link preview, fetched once when the URL is saved (§4 WishLink). The image is a thumbnail only: {PreviewImageKey}_thumb.webp.
    public string? PreviewTitle { get; set; }
    public string? PreviewSiteName { get; set; }
    public string? PreviewImageKey { get; set; }
    public DateTime? PreviewFetchedAt { get; set; }
}

public class WishImage
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public Guid WishId { get; set; }
    /// Files are /data/images/{FileKey}.webp and {FileKey}_thumb.webp.
    public required string FileKey { get; set; }
    public int SortOrder { get; set; }
    public long Bytes { get; set; }
    public required string UploadedByUserId { get; set; }
    public DateTime CreatedAt { get; set; }
}

/// Someone committing to give a wish, alone or as a group (§4).
public class Gift
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public Guid WishId { get; set; }
    public int Units { get; set; } = 1;
    public bool IsGroup { get; set; }
    public GiftStatus Status { get; set; } = GiftStatus.Planned;
    public DateTime CreatedAt { get; set; }
    /// Set after the event date: kept for the Dankesliste, no longer counts towards availability.
    public DateTime? ArchivedAt { get; set; }

    public Wish Wish { get; set; } = null!;
    public List<GiftParticipant> Participants { get; set; } = [];
}

public class GiftParticipant
{
    public Guid GiftId { get; set; }
    public required string UserId { get; set; }
    public bool IsOrganizer { get; set; }
    public decimal? Amount { get; set; }
    public string? Message { get; set; }
    public DateTime JoinedAt { get; set; }
    /// Set while the email is unconfirmed; the participation is released when it passes (§5).
    public DateTime? ExpiresAt { get; set; }
    public int RemindersSent { get; set; }
    /// The device (session) that created it. Unconfirmed users may only change it from there (§5.4).
    public string? DeviceId { get; set; }

    public Gift Gift { get; set; } = null!;
    public AppUser User { get; set; } = null!;
}

public enum LoginCodePurpose { Login, Confirm, Invite }

/// A one-time login: a 6-digit code to type in and a token for links. Only hashes are stored.
public class LoginCode
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public required string UserId { get; set; }
    public required string CodeHash { get; set; }
    public required string TokenHash { get; set; }
    public LoginCodePurpose Purpose { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime ExpiresAt { get; set; }
    public int FailedAttempts { get; set; }
    public DateTime? UsedAt { get; set; }

    public AppUser User { get; set; } = null!;
}

/// Mail waiting to be sent. Written in the same transaction as the action that caused it (§7).
public class OutboxMessage
{
    public Guid Id { get; set; } = Guid.CreateVersion7();
    public required string ToEmail { get; set; }
    public string? ToUserId { get; set; }
    public required string Type { get; set; }
    public required string Subject { get; set; }
    public required string HtmlBody { get; set; }
    public required string TextBody { get; set; }
    public DateTime CreatedAt { get; set; }
    public DateTime NextAttemptAt { get; set; }
    public DateTime? SentAt { get; set; }
    public int Attempts { get; set; }
    public string? LastError { get; set; }
}
